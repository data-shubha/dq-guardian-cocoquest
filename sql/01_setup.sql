CREATE OR REPLACE VIEW DQ_GUARDIAN.DQ.V_LATEST_SCANS AS
SELECT * FROM DQ_GUARDIAN.DQ.SCAN_RUNS
QUALIFY ROW_NUMBER() OVER (PARTITION BY TARGET_FQN ORDER BY RUN_TS DESC) = 1;

CREATE OR REPLACE VIEW DQ_GUARDIAN.DQ.V_OPEN_ISSUES AS
SELECT s.TARGET_FQN, r.SEVERITY, r.DIMENSION, r.RULE_TYPE, r.COLUMN_NAME,
       r.FAILED_ROWS, r.TOTAL_ROWS, ROUND(100 - r.PASS_PCT, 2) AS FAIL_PCT, r.DESCRIPTION
FROM DQ_GUARDIAN.DQ.SCAN_RESULTS r
JOIN DQ_GUARDIAN.DQ.V_LATEST_SCANS s ON s.RUN_ID = r.RUN_ID
WHERE r.STATUS = 'FAIL';

CREATE OR REPLACE TABLE DQ_GUARDIAN.RAW.CUSTOMERS AS
WITH g AS (
  SELECT SEQ4() + 1 AS N FROM TABLE(GENERATOR(ROWCOUNT => 5000))
),
b AS (
  SELECT
    N,
    GET(ARRAY_CONSTRUCT('Aarav','Vivaan','Aditya','Vihaan','Arjun','Sai','Reyansh','Ayaan','Krishna','Ishaan',
                        'Ananya','Diya','Aadhya','Saanvi','Kavya','Riya','Meera','Priya','Sneha','Ishita'),
        MOD(ABS(HASH(N, 'fn')), 20))::STRING AS FNAME,
    GET(ARRAY_CONSTRUCT('Sharma','Patel','Mohanty','Das','Nayak','Reddy','Iyer','Singh','Kumar','Mishra',
                        'Panda','Behera','Rao','Gupta','Joshi'),
        MOD(ABS(HASH(N, 'ln')), 15))::STRING AS LNAME,
    MOD(ABS(HASH(N, 'city')), 10) AS CI,
    GET(ARRAY_CONSTRUCT('Bhubaneswar','Cuttack','Mumbai','Pune','Bengaluru','Chennai','Hyderabad','Kolkata','Delhi','Jaipur'),
        MOD(ABS(HASH(N, 'city')), 10))::STRING AS CITY0,
    GET(ARRAY_CONSTRUCT('Odisha','Odisha','Maharashtra','Maharashtra','Karnataka','Tamil Nadu','Telangana','West Bengal','Delhi','Rajasthan'),
        MOD(ABS(HASH(N, 'city')), 10))::STRING AS STATE0,
    '9' || LPAD(MOD(ABS(HASH(N, 'ph')), 1000000000)::STRING, 9, '0') AS PHONE0,
    (1 + MOD(ABS(HASH(N, 'pin1')), 8))::STRING || LPAD(MOD(ABS(HASH(N, 'pin2')), 100000)::STRING, 5, '0') AS PIN0,
    DATEADD(day, -(7300 + MOD(ABS(HASH(N, 'dob')), 16000)), CURRENT_DATE()) AS DOB0,
    GET(ARRAY_CONSTRUCT('Gold','Silver','Bronze'), MOD(ABS(HASH(N, 'tier')), 3))::STRING AS TIER0
  FROM g
)
SELECT
  N AS CUSTOMER_ID,
  FNAME AS FIRST_NAME,
  LNAME AS LAST_NAME,
  CASE WHEN MOD(N, 37) = 0 THEN NULL
       WHEN MOD(N, 41) = 0 THEN LOWER(FNAME) || N || 'example.com'
       WHEN MOD(N, 53) = 0 THEN '  ' || LOWER(FNAME) || '.' || LOWER(LNAME) || N || '@example.com'
       ELSE LOWER(FNAME) || '.' || LOWER(LNAME) || N || '@example.com' END AS EMAIL,
  CASE WHEN MOD(N, 43) = 0 THEN NULL
       WHEN MOD(N, 61) = 0 THEN LPAD(MOD(ABS(HASH(N, 'sh')), 10000000)::STRING, 7, '0')
       WHEN MOD(N, 29) = 0 THEN '+91-' || PHONE0
       WHEN MOD(N, 67) = 0 THEN SUBSTR(PHONE0, 1, 5) || ' ' || SUBSTR(PHONE0, 6)
       ELSE PHONE0 END AS PHONE,
  CASE WHEN MOD(N, 173) = 0 THEN NULL
       WHEN MOD(N, 211) = 0 THEN DATEADD(year, 3, CURRENT_DATE())
       WHEN MOD(N, 307) = 0 THEN DATE '1850-01-01'
       ELSE DOB0 END AS DATE_OF_BIRTH,
  CITY0 AS CITY,
  CASE WHEN MOD(N, 19) = 0 THEN UPPER(STATE0)
       WHEN MOD(N, 23) = 0 THEN LOWER(STATE0)
       WHEN MOD(N, 89) = 0 THEN SUBSTR(STATE0, 1, 2) || SUBSTR(STATE0, 4)
       ELSE STATE0 END AS STATE,
  CASE WHEN MOD(N, 97) = 0 THEN 'IND'
       WHEN MOD(N, 101) = 0 THEN 'india'
       WHEN MOD(N, 127) = 0 THEN 'INDIA'
       ELSE 'India' END AS COUNTRY,
  CASE WHEN MOD(N, 59) = 0 THEN NULL
       WHEN MOD(N, 71) = 0 THEN LPAD(MOD(ABS(HASH(N, 'pin2')), 100000)::STRING, 5, '0')
       WHEN MOD(N, 83) = 0 THEN 'ABC' || LPAD(MOD(ABS(HASH(N, 'pin2')), 1000)::STRING, 3, '0')
       ELSE PIN0 END AS PINCODE,
  CASE WHEN MOD(N, 199) = 0 THEN DATEADD(day, 10, CURRENT_DATE())
       WHEN MOD(N, 251) = 0 THEN DATEADD(year, 5, DOB0)
       ELSE DATEADD(day, -(1 + MOD(ABS(HASH(N, 'su')), 1500)), CURRENT_DATE()) END AS SIGNUP_DATE,
  CASE WHEN MOD(N, 103) = 0 THEN LOWER(TIER0)
       WHEN MOD(N, 149) = 0 THEN SUBSTR(TIER0, 1, 3) || SUBSTR(TIER0, 5)
       ELSE TIER0 END AS CUSTOMER_TIER,
  (CASE WHEN MOD(N, 97) = 0 THEN -5000
        WHEN MOD(N, 277) = 0 THEN 9999999
        ELSE 10000 + MOD(ABS(HASH(N, 'cl')), 90) * 1000 END)::NUMBER(12,0) AS CREDIT_LIMIT
FROM b;

