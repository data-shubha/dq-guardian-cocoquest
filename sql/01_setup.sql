CREATE OR REPLACE TABLE DQ_GUARDIAN.RAW.ORDERS AS
WITH g AS (
  SELECT SEQ4() + 1 AS N FROM TABLE(GENERATOR(ROWCOUNT => 12000))
),
b AS (
  SELECT
    N,
    1 + MOD(ABS(HASH(N, 'cust')), 5000) AS CUST0,
    DATEADD(day, -(8 + MOD(ABS(HASH(N, 'od')), 720)), CURRENT_DATE()) AS OD0,
    GET(ARRAY_CONSTRUCT('Electronics','Grocery','Fashion','Home','Books','Sports'), MOD(ABS(HASH(N, 'cat')), 6))::STRING AS CAT0,
    1 + MOD(ABS(HASH(N, 'q')), 10) AS Q0,
    ROUND(100 + MOD(ABS(HASH(N, 'p')), 90000) / 100.0, 2) AS P0,
    GET(ARRAY_CONSTRUCT('Delivered','Shipped','Processing','Cancelled','Returned'), MOD(ABS(HASH(N, 'st')), 5))::STRING AS STATUS0
  FROM g
),
c AS (
  SELECT
    N,
    CASE WHEN MOD(N, 127) = 0 THEN 900000 + N ELSE CUST0 END AS CUSTOMER_ID,
    CASE WHEN MOD(N, 241) = 0 THEN DATEADD(day, 30, CURRENT_DATE()) ELSE OD0 END AS ORDER_DATE,
    CAT0,
    CASE WHEN MOD(N, 113) = 0 THEN -Q0 ELSE Q0 END AS QTY,
    CASE WHEN MOD(N, 283) = 0 THEN ROUND(P0 * 100, 2) ELSE P0 END AS PRICE,
    STATUS0,
    OD0
  FROM b
)
SELECT
  N AS ORDER_ID,
  CUSTOMER_ID,
  ORDER_DATE,
  CAT0 AS PRODUCT_CATEGORY,
  QTY AS QUANTITY,
  CASE WHEN MOD(N, 157) = 0 THEN NULL ELSE PRICE END AS UNIT_PRICE,
  CASE WHEN MOD(N, 91) = 0 AND MOD(N, 113) <> 0 AND MOD(N, 283) <> 0
       THEN ROUND(QTY * PRICE, 2) + 10 + MOD(N, 40)
       ELSE ROUND(QTY * PRICE, 2) END AS TOTAL_AMOUNT,
  CASE WHEN MOD(N, 137) = 0 THEN DATEADD(day, -3, ORDER_DATE)
       ELSE DATEADD(day, 1 + MOD(ABS(HASH(N, 'sd')), 7), OD0) END AS SHIP_DATE,
  CASE WHEN MOD(N, 101) = 0 THEN UPPER(STATUS0)
       WHEN MOD(N, 139) = 0 THEN SUBSTR(STATUS0, 1, 3) || SUBSTR(STATUS0, 5)
       ELSE STATUS0 END AS ORDER_STATUS
FROM c;

