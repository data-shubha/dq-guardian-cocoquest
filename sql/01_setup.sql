CREATE DATABASE IF NOT EXISTS DQ_GUARDIAN
  COMMENT = 'CoCoQuest Theme 1 - Agentic Data Quality Guardian';
CREATE SCHEMA IF NOT EXISTS DQ_GUARDIAN.RAW    COMMENT = 'Source tables (with deliberate quality problems)';
